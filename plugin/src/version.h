#pragma once

// Bump these together. LC_VERSION_INTEGER is what xOBSE sees.
#define LC_VERSION_MAJOR    0
#define LC_VERSION_MINOR    22
#define LC_VERSION_PATCH    2
#define LC_VERSION_INTEGER  ((LC_VERSION_MAJOR << 16) | (LC_VERSION_MINOR << 8) | LC_VERSION_PATCH)
#define LC_VERSION_STRING   "0.22.2"
