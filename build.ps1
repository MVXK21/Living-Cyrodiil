# Builds the Living Cyrodiil xOBSE plugin and packages it as a mod folder.
#
# Usage (from the project folder):
#   powershell -ExecutionPolicy Bypass -File .\build.ps1            # Release build
#   powershell -ExecutionPolicy Bypass -File .\build.ps1 -Debug     # Debug build
#
# Output: build\package\  - install this folder as a mod (it contains OBSE\Plugins\LivingCyrodiil.dll)

param([switch]$Debug)

$ErrorActionPreference = 'Stop'
$root   = $PSScriptRoot
$config = if ($Debug) { 'Debug' } else { 'Release' }

function Fail($msg) { Write-Host "BUILD FAILED: $msg" -ForegroundColor Red; exit 1 }

# 1. Make sure the xOBSE source is present (git submodule)
if (-not (Test-Path "$root\external\xOBSE\obse\obse\PluginAPI.h")) {
    Write-Host 'xOBSE source missing; fetching submodule...'
    git -C "$root" submodule update --init --recursive
    if ($LASTEXITCODE -ne 0) { Fail 'could not fetch the xOBSE submodule' }
}

# 2. Find Visual Studio's MSBuild
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
if (-not (Test-Path $vswhere)) { Fail 'Visual Studio is not installed (see docs/setup.md)' }

$vsPath = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Workload.NativeDesktop -property installationPath
if (-not $vsPath) { Fail "the 'Desktop development with C++' workload is missing (see docs/setup.md)" }

# Check for the actual files: component names differ between Visual Studio versions.
# The v142 toolset is MSVC 14.2x.
$v142 = Get-ChildItem "$vsPath\VC\Tools\MSVC" -Directory -Filter '14.2*' -ErrorAction SilentlyContinue |
        Where-Object { Test-Path "$($_.FullName)\bin\Hostx64\x86\cl.exe" } | Sort-Object Name | Select-Object -Last 1
if (-not $v142) { Fail "the 'MSVC v142 - VS 2019 C++ x64/x86 build tools' component is missing (see docs/setup.md)" }
if (-not (Test-Path "$($v142.FullName)\atlmfc\include\atltypes.h")) {
    Fail "the 'C++ ATL for v142 build tools (x86 & x64)' component is missing (see docs/setup.md). Note: plain 'C++ ATL' is for the newest toolset, not v142."
}
Write-Host "Using MSVC $($v142.Name) (v142 toolset)"

$msbuild = Join-Path $vsPath 'MSBuild\Current\Bin\MSBuild.exe'
if (-not (Test-Path $msbuild)) { Fail "MSBuild not found at $msbuild" }

# 3. Build (32-bit only)
Write-Host "Building $config|Win32 with $msbuild"
& $msbuild "$root\plugin\LivingCyrodiil.sln" /m /nologo /v:minimal "/p:Configuration=$config" /p:Platform=Win32
if ($LASTEXITCODE -ne 0) { Fail 'compile errors (see output above)' }

# 4. Package as a mod folder
$dll = "$root\build\$config\LivingCyrodiil.dll"
if (-not (Test-Path $dll)) { Fail "expected output $dll was not created" }

$pkg = "$root\build\package"
$plugins = "$pkg\OBSE\Plugins"
if (Test-Path $pkg) { Remove-Item -Recurse -Force $pkg }
New-Item -ItemType Directory -Force $plugins | Out-Null
Copy-Item $dll $plugins
Copy-Item "$root\plugin\LivingCyrodiil.ini" $plugins

# The placeholder-dialogue plugin, generated by script (never hand-edited)
& py -3 "$root\tools\build_esp.py" "$pkg\LivingCyrodiil.esp"
if ($LASTEXITCODE -ne 0) { Fail 'building LivingCyrodiil.esp failed' }
Copy-Item "$root\build\$config\LivingCyrodiil.pdb" $plugins -ErrorAction SilentlyContinue  # helps read crash dumps

Write-Host ''
Write-Host "BUILD OK ($config): $plugins\LivingCyrodiil.dll" -ForegroundColor Green
